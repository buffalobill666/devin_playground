"""dynasty.py — sixth cartographic genre: dynastic history.

Political map was static; dialect map was spatial. This one is
TEMPORAL: the continent as a document of succession. Dynasties
are founded at hearths, expand into habitable land, fragment
by inheritance when too large (cadet branches — same hue
family, new name), and sometimes go extinct (land reverts
to wilderness or is eaten by neighbors).

The map is genealogical, not political: colors are chosen so
kinship is visible — a cadet branch inherits the parent hue,
shifted. Inset: the dynastic tree itself, time downward,
extinctions marked with x. Names generated by mu.
"""
import sys
import os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'conlang'))
import random
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from continent import continent, moisture
from gen import word

N = 256
rng = random.Random(41)
np_rng = np.random.default_rng(41)

EPOCHS = 60
SPLIT_SIZE = 700      # cells; inheritance fragments beyond this
EXPAND_P = 0.55       # growth pressure


def habit(h, m):
    """habitability 0..1 — lowland, moist but not swamp."""
    hab = (1 - abs(h - 0.35)) * (1 - abs(m - 0.55) * 0.7)
    hab[h > 0.75] *= 0.15      # mountains hostile
    hab[h < 0.18] = 0          # sea
    return np.clip(hab, 0, 1)


def mu_name():
    return ''.join(word(rng) for _ in range(1))[:6].capitalize()


def simulate(h, m):
    hab = habit(h, m)
    land = hab > 0.25
    # founding hearth: max hab in south-west quadrant region
    ys, xs = np.where(land)
    owner = np.full((N, N), -1, dtype=int)   # dynasty id per cell
    dynasties = {}   # id -> dict(name, hue, parent, born, died, cells)
    nid = [0]

    def found(y, x, parent, epoch):
        i = nid[0]; nid[0] += 1
        base_hue = rng.random() if parent is None else dynasties[parent]['hue'] + rng.uniform(-0.09, 0.09)
        dynasties[i] = dict(name=mu_name(), hue=base_hue % 1.0, parent=parent,
                            born=epoch, died=None, cells={(y, x)})
        owner[y, x] = i
        return i

    # first founders: 3 spaced seeds
    cands = sorted(zip(ys, xs), key=lambda p: -hab[p])
    seeds = []
    for y, x in cands:
        if all((y - yy) ** 2 + (x - xx) ** 2 > 45 ** 2 for yy, xx in seeds):
            seeds.append((y, x))
        if len(seeds) == 3:
            break
    for sy, sx in seeds:
        found(sy, sx, None, 0)

    extinct_events = []
    for epoch in range(1, EPOCHS):
        for did in list(dynasties):
            d = dynasties[did]
            if d['died'] is not None:
                continue
            # expansion: claim habitable neighbors of owned cells
            frontier = []
            for (y, x) in d['cells']:
                for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    ny, nx = y + dy, x + dx
                    if 0 <= ny < N and 0 <= nx < N and land[ny, nx] and owner[ny, nx] == -1:
                        frontier.append((ny, nx))
            rng.shuffle(frontier)
            take = min(len(frontier), max(2, len(d['cells']) // 6))
            for ny, nx in frontier[:take]:
                owner[ny, nx] = did
                d['cells'].add((ny, nx))
            # inheritance fragmentation
            if len(d['cells']) > SPLIT_SIZE and rng.random() < 0.5:
                # inheritance division: cadet branch carved contiguously
                seed = rng.choice(sorted(d['cells']))
                child = found(seed[0], seed[1], did, epoch)
                dynasties[child]['cells'] = set()
                stack = [seed]
                taken = 0
                while stack and taken < len(d['cells']) // 2:
                    cy, cx = stack.pop()
                    if (cy, cx) in dynasties[child]['cells']:
                        continue
                    if owner[cy, cx] != did and owner[cy, cx] != child:
                        continue
                    dynasties[child]['cells'].add((cy, cx))
                    owner[cy, cx] = child
                    d['cells'].discard((cy, cx))
                    taken += 1
                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                        ny2, nx2 = cy + dy, cx + dx
                        if 0 <= ny2 < N and 0 <= nx2 < N and owner[ny2, nx2] == did                                 and (ny2, nx2) not in dynasties[child]['cells']:
                            stack.append((ny2, nx2))
            # extinction: rare, big dynasties slightly protected
            if rng.random() < 0.008 and epoch > 12 and len(d['cells']) < 300:
                d['died'] = epoch
                extinct_events.append((did, epoch))
                for (y, x) in list(d['cells']):
                    owner[y, x] = -1
                d['cells'] = set()
    return owner, dynasties, land


def render(h, owner, dynasties, land, path):
    import colorsys
    img = np.zeros((N, N, 3), dtype=np.uint8)
    # sea
    img[~land] = (26, 44, 68)
    # wilderness
    img[land & (owner == -1)] = (76, 82, 66)
    for did, d in dynasties.items():
        r, g, b = colorsys.hsv_to_rgb(d['hue'], 0.52, 0.82)
        mask = owner == did
        img[mask] = (int(r * 255), int(g * 255), int(b * 255))
    # dynastic borders: different owner on any side -> darkened edge
    own = owner.astype(int)
    diff = np.zeros_like(own, dtype=bool)
    diff[:-1, :] |= own[:-1, :] != own[1:, :]
    diff[1:, :] |= own[:-1, :] != own[1:, :]
    diff[:, :-1] |= own[:, :-1] != own[:, 1:]
    diff[:, 1:] |= own[:, :-1] != own[:, 1:]
    edge = diff & (own >= 0)
    img[edge] = (img[edge].astype(int) * 2 // 5).astype(np.uint8)
    im = Image.fromarray(img).resize((512, 512), Image.NEAREST)
    out = Image.new('RGB', (860, 560), (24, 24, 30))
    out.paste(im, (20, 24))
    dr = ImageDraw.Draw(out)
    try:
        F = ImageFont.truetype('C:/Windows/Fonts/consola.ttf', 13)
        FB = ImageFont.truetype('C:/Windows/Fonts/consola.ttf', 16)
    except Exception:
        F = FB = ImageFont.load_default()
    dr.text((20, 4), 'NOTU — dynastic succession, 60 epochs', font=FB, fill=(230, 226, 210))
    # dynastic tree inset, x 550..850, time downward
    x0, y0 = 560, 60
    dr.text((x0, 30), 'dynastic tree', font=FB, fill=(230, 226, 210))
    import colorsys
    n_d = len(dynasties)
    # simple layered layout: order by birth epoch, x by founder order
    ids = sorted(dynasties, key=lambda i: (dynasties[i]['born'], i))
    depth = {}
    for i in ids:
        p = dynasties[i]['parent']
        depth[i] = 0 if p is None else depth.get(p, 0) + 1
    xs, cursors = {}, {}
    lanes = {}
    lane_at = {}
    # assign lanes per depth level
    # time runs downward: y = birth epoch. x: lanes assigned
    # by a greedy non-overlap pass per epoch.
    maxborn = max(dynasties[i]['born'] for i in ids) or 1
    by_epoch = {}
    for i in ids:
        by_epoch.setdefault(dynasties[i]['born'], []).append(i)
    pos = {}
    lane_of = {}
    lanes_free_at = []   # lane -> epoch when it becomes free
    for epoch in sorted(by_epoch):
        for i in sorted(by_epoch[epoch]):
            # reuse the lane freed earliest, else open a new one
            cand = [l for l, fr in enumerate(lanes_free_at) if fr <= epoch]
            if cand:
                lane = min(cand, key=lambda l: lanes_free_at[l])
            else:
                lane = len(lanes_free_at)
                lanes_free_at.append(0)
            lanes_free_at[lane] = epoch + 9   # keep label room
            lane_of[i] = lane
    nlanes = max(1, len(lanes_free_at))
    for i in ids:
        span = 268
        step = span / max(1, nlanes)
        x = x0 + 6 + lane_of[i] * step
        y = y0 + (dynasties[i]['born'] / maxborn) * 430 + 4
        pos[i] = (int(x), int(y))
    for i in ids:
        x, y = pos[i]
        d = dynasties[i]
        r, g, b = colorsys.hsv_to_rgb(d['hue'], 0.52, 0.9)
        col = (int(r * 255), int(g * 255), int(b * 255))
        if d['parent'] is not None and d['parent'] in pos:
            px, py = pos[d['parent']]
            dr.line((px, py, x, y), fill=(120, 118, 110), width=1)
        dr.ellipse((x - 4, y - 4, x + 4, y + 4), fill=col)
        lbl = d['name'][:8] + (' x' if d['died'] is not None else '')
        dr.text((x + 7, y - 6), lbl, font=F, fill=(200, 196, 180))
    out.save(path)
    print(f'{path} written: {len(dynasties)} dynasties, '
          f'{sum(1 for d in dynasties.values() if d["died"])} extinct, '
          f'covering {np.sum(owner >= 0)} cells')


if __name__ == '__main__':
    h = continent(N)
    m = moisture(N)
    owner, dynasties, land = simulate(h, m)
    render(h, owner, dynasties, land, 'maps/dynasty.png')
