"""kakuro.py — kakuro generator + uniqueness proof. Genre #5.

The twist vs sudoku/skyscraper: kakuro clues are the run
sums themselves — they cannot be greedily dropped. So the
uniqueness law survives by changing its carving protocol:
here posing is rejection — plant a consistent fill, read off
the sums, prove the sums alone have exactly one completion.
No digit hints: purist kakuro.

Grid: white cells in runs of length 2..K across and down;
every white cell belongs to exactly one across-run and one
down-run. Layout is generated by growing runs on a small
board. Solver: each run's domain = distinct-digit tuples
summing to the clue; backtrack runs in order of domain size.
"""
import random
from itertools import permutations

DIG = tuple(range(1, 10))


def run_combos(total, length):
    out = []
    for p in permutations(DIG, length):
        if sum(p) == total:
            out.append(p)
    return out


def make_layout(rng, W=5, H=5, blackp=0.34):
    """Sprinkle black cells, then iteratively cull any white cell
    not doubly covered (length-1 runs and edge strips die out).
    Simple, dense, and the overlap constraint does the work."""
    white = [[1 if rng.random() > blackp else 0
              for _ in range(W)] for _ in range(H)]
    for _ in range(12):
        runs = extract_runs(white, W, H)
        cover = {}
        for r in runs:
            if len(r[2]) >= 2:
                for c in r[2]:
                    cover[c] = cover.get(c, 0) + 1
        changed = False
        for y in range(H):
            for x in range(W):
                if white[y][x] and cover.get((y, x), 0) != 2:
                    white[y][x] = 0
                    changed = True
        if not changed:
            break
    runs = [r for r in extract_runs(white, W, H) if len(r[2]) >= 2]
    ncells = sum(sum(r) for r in white)
    # every remaining white cell must be in exactly 2 runs
    cover = {}
    for r in runs:
        for c in r[2]:
            cover[c] = cover.get(c, 0) + 1
    if (len(runs) >= 6 and ncells >= 8
            and len(cover) == ncells
            and all(v == 2 for v in cover.values())):
        return white, runs, W, H
    return None


def extract_runs(white, W, H):
    runs = []
    for y in range(H):
        x = 0
        while x < W:
            if white[y][x]:
                xs = [x]
                while x + 1 < W and white[y][x + 1]:
                    x += 1; xs.append(x)
                if len(xs) >= 2:
                    runs.append(('A', len(runs), [(y, xx) for xx in xs]))
                x += 1
            else:
                x += 1
    for x in range(W):
        y = 0
        while y < H:
            if white[y][x]:
                ys = [y]
                while y + 1 < H and white[y + 1][x]:
                    y += 1; ys.append(y)
                if len(ys) >= 2:
                    runs.append(('D', len(runs), [(yy, x) for yy in ys]))
                y += 1
            else:
                y += 1
    return runs


def plant(rng, runs):
    """Random consistent fill: assign run tuples consistent on
    shared cells, backtracking."""
    order = sorted(range(len(runs)),
                   key=lambda i: -len(runs[i][2]))
    assign = {}
    cellval = {}
    def bt(k):
        if k == len(order):
            return True
        ri = order[k]
        cellspec = runs[ri][2]
        dom = list(permutations(DIG, len(cellspec)))
        rng.shuffle(dom)
        for tup in dom:
            ok = True
            for pos, c in enumerate(cellspec):
                if c in cellval and cellval[c] != tup[pos]:
                    ok = False; break
            if ok:
                assign[ri] = tup
                newly = []
                for pos, c in enumerate(cellspec):
                    if c not in cellval:
                        cellval[c] = tup[pos]
                        newly.append(c)
                if bt(k + 1):
                    return True
                del assign[ri]
                for c in newly:
                    cellval.pop(c, None)
        return False
    if bt(0):
        return {c: cellval[c] for r in runs for c in r[2]}, assign
    return None, None


def solve_count(runs, sums, limit=2):
    """Count completions consistent with run sums, cap `limit`.
    Arc-consistency first: iteratively prune run tuples whose
    digits no other run can match at the shared cell."""
    doms = []
    for i, (_, _, cellspec) in enumerate(runs):
        doms.append([p for p in run_combos_fast(sums[i], len(cellspec))])
    if any(not d for d in doms):
        return 0
    # cell -> list of (run_idx, pos)
    celluse = {}
    for i, (_, _, cellspec) in enumerate(runs):
        for pos, c in enumerate(cellspec):
            celluse.setdefault(c, []).append((i, pos))
    changed = True
    while changed:
        changed = False
        for c, uses in celluse.items():
            # possible values at c = intersection of what each run allows
            per_run = []
            for ri, pos in uses:
                per_run.append({t[pos] for t in doms[ri]})
            if not per_run:
                continue
            inter = set.intersection(*per_run) if len(per_run) > 1 else per_run[0]
            for ri, pos in uses:
                before = len(doms[ri])
                doms[ri] = [t for t in doms[ri] if t[pos] in inter]
                if len(doms[ri]) != before:
                    changed = True
        if any(not d for d in doms):
            return 0
    order = sorted(range(len(runs)), key=lambda i: len(doms[i]))
    cellval = {}
    count = 0
    def bt(k):
        nonlocal count
        if count >= limit:
            return
        if k == len(order):
            count += 1
            return
        ri = order[k]
        cellspec = runs[ri][2]
        for tup in doms[ri]:
            ok = True
            for pos, c in enumerate(cellspec):
                if c in cellval and cellval[c] != tup[pos]:
                    ok = False; break
            if ok:
                newly = []
                for pos, c in enumerate(cellspec):
                    if c not in cellval:
                        cellval[c] = tup[pos]
                        newly.append(c)
                bt(k + 1)
                for c in newly:
                    cellval.pop(c, None)
    bt(0)
    return count


_combo_cache = {}
def run_combos_fast(total, length):
    key = (total, length)
    if key not in _combo_cache:
        _combo_cache[key] = [p for p in permutations(DIG, length)
                             if sum(p) == total]
    return _combo_cache[key]


def generate(seed=5):
    rng = random.Random(seed)
    for attempt in range(60):
        lay = make_layout(rng)
        if not lay:
            continue
        white, runs, W, H = lay
        fill, assign = plant(rng, runs)
        if not fill:
            continue
        sums = [sum(assign[i]) for i in range(len(runs))]
        n = solve_count(runs, sums, limit=2)
        if n == 1:
            return white, runs, sums, W, H, fill, attempt
    return None


if __name__ == '__main__':
    res = generate()
    if not res:
        print('no unique puzzle found in 60 attempts')
    else:
        white, runs, sums, W, H, fill, att = res
        print(f'UNIQUE kakuro found at attempt {att}: '
              f'{len(runs)} runs, {sum(sum(r) for r in white)} cells')
        for y in range(H):
            row = ''
            for x in range(W):
                row += str(fill[(y, x)]) if white[y][x] else '#'
            print(' ', row)
        print('run sums:', sums)
