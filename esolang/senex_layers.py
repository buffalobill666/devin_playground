"""senex_layers.py — карта слоёв RENEW: эмпирика закона продления.

Генератор k-слойной программы: тело цикла (PUSH/ADD/PRINT/JMP)
+ k слоёв обслуживания. Слой 1 — RENEW на каждую клетку тела;
слой m — RENEW на каждую клетку слоя m-1.

ЭМПИРИЧЕСКИЙ ЗАКОН (проверен на 15 точках, точное попадание):
    steps = 2 * life * (k+1) * (k+2)      (k>=1; k=0: +1 за init)
каждый слой даёт ровно life/2 круга жизни — продление ЛИНЕЙНО
по слоям при ЛИНЕЙНОМ росте программы (+4 клетки/слой).

КОНТРОЛЬ, который всё это дал: первый вариант build() не
покрывал JMP-клетку — loops вышли на плато 3.6-3.8 при любом k:
оголённый хвост обнуляет всю глубину слоёв. Плато — это
теорема, увиденная до формулы.

Строгое доказательство теоремы SENEX:

ДОКАЗАТЕЛЬСТВО (подсчёт покрытия). Пусть множество исполняемых
клеток E, |E|=n. Каждая исполняемая клетка стареет и чтобы жить
вечно нуждается в покрытии: >=1 RENEW, направленный на неё.
RENEW-клетка покрывает ровно один адрес (arg зафиксирован).
Значит RENEW-клеток нужно >= n. Но цикл обязан содержать
как минимум одну не-RENEW клетку (JMP/JZ — иначе нет
возврата) -> RENEW-клеток <= n-1 -> по принципу Дирихле
хотя бы одна клетка не покрыта -> она прогорает -> каскад.
Само-восстановление (RENEW self) спасает лишь саму клетку —
счёт не меняет. QED: бессмертие невозможно структурно.

Запуск: карта life x layers.
"""

from senex import assemble, run


def build(k):
    """k-слойная программа: каждый слой покрывает ВСЕ клетки
    предыдущего уровня, включая JMP (иначе хвост оголён и
    слои бесполезны — эмпирика показала плато loops).
    Лента: [init][тело 3][L1 4][L2 4]...[Lk 4][JMP]"""
    lines = ['      PUSH 0', 'loop: PUSH 1', '      ADD',
             '      PRINT']
    jmp_idx = 4 + 4 * k                       # JMP — последняя
    targets = [1, 2, 3, jmp_idx]              # тело + JMP
    for _layer in range(k):
        new_targets = []
        for t in targets:
            new_targets.append(len(lines))
            lines.append(f'      RENEW {t}')
        targets = new_targets
    assert len(lines) == jmp_idx
    lines.append('      JMP loop')
    return '\n'.join(lines)


if __name__ == '__main__':
    print('k\\life |', '  '.join(f'{L:>5}' for L in (2, 3, 5)))
    for k in range(0, 5):
        src = build(k)
        tape = assemble(src)
        row = []
        for L in (2, 3, 5):
            steps, out, dead = run(tape, life=L, cap=6000)
            row.append(steps)
        print(f'  {k}   |', '  '.join(f'{s:>5}' for s in row),
              f'(клеток: {len(tape)})')
    print('ожидание: loops ~= (k+1)*life — каждый слой +1 срок')
