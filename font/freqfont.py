H = 8  # высота глифа


def text_width(text, spacing=1):
    return sum(len(GLYPHS.get(c, GLYPHS[' '])[0]) + spacing
               for c in text.upper()) - spacing


def render_lines(lines, scale=8, spacing=1, pad=12):
    """Рендер списка строк в PNG-массив -> PIL image."""
    from PIL import Image
    w = max(text_width(l) for l in lines) + pad * 2
    h = len(lines) * (H + 2) + pad * 2
    img = Image.new('RGB', (w * scale // 8 if scale < 8 else w * scale,
                            h * scale // 8 if scale < 8 else h * scale),
                    (240, 237, 230))
    # проще: рисуем в исходном размере, потом увеличиваем
    img = Image.new('RGB', (w, h), (240, 237, 230))
    for li, line in enumerate(lines):
        x = pad
        y = pad + li * (H + 2)
        for c in line.upper():
            g = GLYPHS.get(c, GLYPHS[' '])
            for ry, row in enumerate(g):
                for rx, px in enumerate(row):
                    if px == '#':
                        img.putpixel((x + rx, y + ry), (26, 38, 63))
            x += len(g[0]) + spacing
    return img.resize((w * scale, h * scale), Image.NEAREST)


